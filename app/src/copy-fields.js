export const defaultSubtitles = Object.fromEntries(copyFields.map(([, key, , value]) => [key, value]));
export function normalizeContent(config) {
  const subtitles = { ...defaultSubtitles, ...config.subtitles };
  for (const key of ['envelopeAddressee', 'letterAddressee']) {
    if (config.subtitles?.[key] === undefined) subtitles[key] = config.greeting ?? '致xxx';
  }
  return { ...config, subtitles };
}

